/**
 * Самый длинный запрос поиска текста. Длиннее - уже не строка, а вставленный кусок
 * файла: окно такой не отправляет и говорит об этом, главный процесс - отвергает.
 */
export const TEXT_QUERY_MAX_LENGTH = 200

/**
 * Все файлы проекта для поиска по имени: пути от корня через «/», в NFC (как и пути
 * дерева файлов, их можно сравнивать строками). Игнорируемое git (.gitignore) сюда
 * не попадает, папки без git - без служебных и тяжёлых каталогов.
 */
export type ProjectFileList = {
  paths: string[]
  /** Файлов больше предела - список обрезан, и найдётся не всё. */
  truncated: boolean
}

/** Одна строка проекта, где встретился искомый текст. */
export type TextMatch = {
  /** Путь от корня проекта через «/», в NFC - как в ProjectFileList и дереве файлов. */
  relativePath: string
  /** Номер строки с 1. */
  line: number
  /** Кусок строки вокруг совпадения: длинные строки (минифицированный код) обрезаны. */
  preview: string
  /** Где в preview совпадение: начало и длина в символах. */
  matchStart: number
  matchLength: number
}

export type TextSearchResult = {
  matches: TextMatch[]
  /** Совпадений больше предела или поиск не уложился во время - показано не всё. */
  truncated: boolean
}
