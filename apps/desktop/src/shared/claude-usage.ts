/**
 * Лимиты подписки Claude по аккаунту (ADR 0009): окна расхода, как их называет сервер
 * в ответе CLI на `get_usage`, и доплата сверх тарифа.
 */

/** Окно лимита: пять часов, неделя, неделя одной модели. */
export type UsageWindow = {
  /** session - пять часов, weekly - неделя; прочее - как назвал сервер. */
  group: string
  /** Модель окна (Fable) - у недели одной модели; пусто - окно всего тарифа. */
  model: string
  /** Сколько израсходовано, проценты; бывает больше 100 при доплате. */
  percent: number
  /** Когда окно сбросится (мс); null - сервер не сказал. */
  resetsAt: number | null
  /** Насколько близко к пределу словами сервера: normal, warning, critical. */
  severity: string
}

/** Расход аккаунта: окна, доплата (если включена) и когда цифры сняты с сервера (мс). */
export type AccountUsage = {
  windows: UsageWindow[]
  /** Доплата сверх тарифа включена: сколько от месячного предела потрачено; null - не сказано. */
  extra: { percent: number | null } | null
  fetchedAt: number
}
