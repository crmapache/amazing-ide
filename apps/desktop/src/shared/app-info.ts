/** То, что окну нужно знать о самом приложении и машине. */
export type AppInfo = {
  version: string
  /** Собранное приложение, а не dev-режим. */
  isPackaged: boolean
  /** Домашняя папка: пути проектов в меню показываются через ~. */
  homeDir: string
  /** Документы: куда по умолчанию класть новый или склонированный проект. */
  documentsDir: string
}

/** Сколько машины занимают сейчас все процессы IDE вместе. */
export type ResourceUsage = {
  /**
   * Процессор как в «Мониторинге системы»: 100 - одно ядро целиком, поэтому на
   * нескольких ядрах бывает больше 100. Среднее с прошлого замера.
   */
  cpuPercent: number
  /**
   * Память в байтах - физический след процессов, как в «Мониторинге системы». null -
   * не измерить: нативный вызов macOS не загрузился.
   */
  memoryBytes: number | null
}
