/**
 * Пунктуация фразы, прилипшая к пути, и «@», которым пишутся упоминания файлов: путь в
 * конце предложения держит точку, в скобках - скобку, и ни то ни другое не часть имени.
 */
export const EDGE_PUNCTUATION = /^[@(["']+|[).,;:"'\]]+$/g

/**
 * Место в конце ссылки: `:120`, `:120:4`, диапазоны `:120-130`, `:120:33-40`,
 * `:12-18:5-30`. Группы: строка, конец строк, колонка, конец колонок.
 */
export const PLACE_SUFFIX = /:(\d+)(?:-(\d+))?(?::(\d+)(?:-(\d+))?)?$/

/** Буква диска в начале - единственное место, где двоеточие принадлежит пути. */
export const DRIVE_PREFIX = /^[A-Za-z]:[\\/]/

/** Чего в пути не бывает: пробелы, звёздочки и вопросы глоба, перенаправления оболочки. */
export const FORBIDDEN_IN_PATH = /[\s*?"<>|]/

/**
 * Имя из точки и слова: `.claude`, `.venv`, `.gitignore`. Папка это или файл, по форме
 * не сказать - говорит список известных дот-файлов: что в нём, то файл, остальное - папка.
 */
export const DOT_NAME = /^\.[A-Za-z][A-Za-z0-9]{0,14}$/

/** Путь от корня диска или дома: `/var/log`, `C:\Users`, `~/.claude`. */
export const ROOTED_PATH = /^(?:[/\\]|~[/\\]|[A-Za-z]:[\\/])/

/** Расширение последнего куска: буквы, потом буквы или цифры - не `247` версии. */
export const NAME_EXTENSION = /\.([A-Za-z][A-Za-z0-9]{0,14})$/

/** Слова текста: путь в предложении кончается там, где начинается пробел. */
export const WORDS = /\S+/g

/** Адрес сайта в тексте. Схемы, кроме http(s), ссылками не становятся. */
export const WEB_ADDRESS = /https?:\/\/\S+/g

/** Знаки конца фразы, которые не часть адреса: «см. https://example.com.» */
export const ADDRESS_TRAILING = `.,!?;:'"`

/**
 * Сколько лента верит списку файлов проекта, прежде чем спросить снова. Список - лишь
 * подсказка, какое голое имя сделать ссылкой (решает клик - он спрашивает диск), а
 * собирается он git'ом по всему проекту: перечитывать его на каждую новую строку ленты
 * незачем. Поиск и «@» освежают тот же кэш чаще.
 */
