/**
 * Расширения картинок: «@путь.png» из транскрипта - чип картинки, а не файла. Тот же
 * список, что у главного процесса для выбранных файлов (main/claude/composer).
 */
export const PICTURE_EXTENSIONS: ReadonlySet<string> = new Set([
  'png',
  'jpg',
  'jpeg',
  'gif',
  'webp',
  'bmp',
  'svg',
])

/** Короче этого кавычки не отличить от обычной пунктуации - это не цитата ответа. */
export const QUOTATION_MIN = 40

/**
 * «@путь» и подпись вставленной картинки - то, что поле пишет само. «@» - в начале
 * строки, после пробела или скобки: почта «me@host.com» - не путь.
 */
export const REPLAY_ATTACHMENT = /\[Image #\d+\]|(?<=^|[\s(])@\S+/g

/** Пунктуация фразы после пути принадлежит фразе. */
export const REPLAY_TRAILING = /[.,;:!?)\]}"']+$/

/** Строки куска файла сразу за путём: «@путь (L12-L18)». */
export const REPLAY_RANGE = /^ \((L[^)]*)\)/

/** Команда в начале сообщения: «/review», «/plugin:skill» - и пробел или конец за ней. */
export const REPLAY_COMMAND = /^\/([A-Za-z0-9][\w:.-]*)(?=\s|$)/

export const REPLAY_QUOTATION = /"([^"]+)"/g

/**
 * Сколько вставки рисуется раскрытой: стокилобайтный лог в ленте перерисовывался бы на
 * каждый кусок печатающегося ответа. Копия берёт вставку целиком.
 */
export const PASTE_OPEN_CHARS = 20_000

/** Сколько символов вставки в свёрнутой плашке во всю ширину: экран всё равно режет до трёх строк. */
export const PASTE_BLOCK_CHARS = 600

/**
 * Строки куска файла, как их пишет поле: `L12`, `L12-L18`, `L12:5-30`, `L12:5-L18:30`.
 * Чужая подпись - не диапазон: файл откроется сверху, а не где-то наугад.
 */
export const RANGE_LABEL = /^L(\d+)(?::(\d+))?(?:-(?:L(\d+)(?::(\d+))?|(\d+)))?$/
