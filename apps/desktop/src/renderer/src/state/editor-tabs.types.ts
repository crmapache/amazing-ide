/**
 * Вкладки середины окна одного проекта. Ключ вкладки - путь файла (от корня проекта, а у
 * файла вне проекта, открытого ссылкой, - абсолютный) или ключ вкладки разницы
 * (diffTabKey). keys - в порядке открытия, он же порядок на полосе: первая в нём - самая
 * давняя, её и закрывает переполнение. recent - те же ключи в порядке выбора,
 * последний - активный: закрыл активную - открылась та, что была до неё.
 */
export type EditorTabs = {
  keys: string[]
  recent: string[]
}

/**
 * Что показывает вкладка: файл в редакторе или его разницу с последним коммитом, как
 * «Commit: файл» в WebStorm. Путь - от корня проекта; у файла вне проекта - абсолютный
 * (разницы у него не бывает: git проекта его не знает).
 */
export type TabTarget = { kind: 'file' | 'diff'; path: string }
