import type { ReactNode } from 'react'

export type MenuProps = {
  /** Подпись для скринридера: что это за меню. */
  label: string
  /**
   * При появлении поставить фокус: на элемент с data-autofocus (поле поиска), на
   * выбранный пункт (`current`) или на первый доступный. С выбранного - как в меню
   * macOS: Enter сразу после открытия оставляет выбор как есть, а не берёт верхний.
   * Меню во всплывающей панели монтируется при открытии. Меню, которое стояло
   * спрятанным (раздел панели за вкладкой), получает фокус, когда autoFocus
   * становится true.
   */
  autoFocus?: boolean
  /**
   * Над пунктами, стоит на месте при прокрутке: поле поиска. Меню во всплывающей
   * панели - шапка ложится вровень с её краями.
   */
  header?: ReactNode | undefined
  children: ReactNode
}
